  code TEXT PRIMARY KEY NOT NULL CHECK(length(code)=2),
  name TEXT NOT NULL UNIQUE CHECK(length(trim(name)) BETWEEN 1 AND 100)
);
CREATE TABLE administrative_wards (
  code TEXT PRIMARY KEY NOT NULL CHECK(length(code)=5),
  province_code TEXT NOT NULL REFERENCES administrative_provinces(code) ON DELETE RESTRICT,
  name TEXT NOT NULL CHECK(length(trim(name)) BETWEEN 1 AND 100),
  UNIQUE(province_code,name)
);
